def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out-dir", default=ROOT / "paper" / "tables", type=Path)
    args = parser.parse_args()

    w6 = read(ROOT / "baseline" / "sf100-matrix-20260613-cn.md")
    w7 = read(ROOT / "baseline" / "w7-sf30-workload-shift-summary-20260615-cn.md")
    w8 = read(ROOT / "baseline" / "w8-property-2hop-summary-20260615-cn.md")
    w9 = read(ROOT / "baseline" / "w9-steady-state-summary-20260615-cn.md")
    w13 = read(ROOT / "baseline" / "w13-schema-evolution-summary-20260614.md")

    render_evidence_overview(args.out_dir)
    render_w6(w6, args.out_dir)
    render_w7(w7, args.out_dir)
    render_w8(w8, args.out_dir)
    render_w9(w9, args.out_dir)
    render_w13(w13, args.out_dir)
    render_caveats(args.out_dir)
    render_artifact_map(args.out_dir)


if __name__ == "__main__":
    main()
