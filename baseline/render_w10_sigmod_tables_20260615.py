#!/usr/bin/env python3
"""Render W10 SIGMOD-oriented TeX tables from frozen regenerated reports.

The input reports are themselves regenerated from raw W6/W7/W8/W9 JSON, TSV, and
JSONL artifacts by the matching summarizers. This renderer keeps the paper source
from hand-copying table numbers while preserving the W10 claim boundaries.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def strip_cell(cell: str) -> str:
    cell = cell.strip()
    if cell.startswith("`") and cell.endswith("`"):
        cell = cell[1:-1]
    return cell


def md_table_after(text: str, heading: str) -> list[dict[str, str]]:
    lines = text.splitlines()
    start = None
    for idx, line in enumerate(lines):
        if line.strip() == heading:
            start = idx + 1
            break
    if start is None:
        raise SystemExit(f"missing heading: {heading}")
    while start < len(lines) and not lines[start].lstrip().startswith("|"):
        start += 1
    if start + 1 >= len(lines):
        raise SystemExit(f"missing table after heading: {heading}")
    header = [strip_cell(c) for c in lines[start].strip().strip("|").split("|")]
    rows: list[dict[str, str]] = []
    idx = start + 2
    while idx < len(lines) and lines[idx].lstrip().startswith("|"):
        cells = [strip_cell(c) for c in lines[idx].strip().strip("|").split("|")]
        if len(cells) == len(header):
            rows.append(dict(zip(header, cells)))
        idx += 1
    return rows


def tex_escape(text: str) -> str:
    repl = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(repl.get(ch, ch) for ch in str(text))


def short_metric(text: str) -> str:
    first = str(text).split("+/-")[0].strip()
    return tex_escape(first)


def write_file(path: Path, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body.rstrip() + "\n", encoding="utf-8")


def table_env(label: str, caption: str, tabular: str, size: str = r"\small") -> str:
    return "\n".join(
        [
            "% Auto-generated by baseline/render_w10_sigmod_tables_20260615.py.",
            r"\begin{table}[t]",
            r"\centering",
            size,
            rf"\caption{{{caption}}}",
            rf"\label{{{label}}}",
            tabular,
            r"\end{table}",
            "",
        ]
    )


def render_evidence_overview(out_dir: Path) -> None:
    rows = [
        ("W6", "SF100 matrix", "measured", "Gate 1 FALLBACK; Gate 2 GO"),
        ("W7", "workload shift", "real-SF30-derived", "Gate=GO; not production trace"),
        ("W8", "property and 2-hop", "measured SF30", "2-hop candidate count mixed"),
        ("W9", "mixed read/write", "measured SF30", "steady-state coverage"),
        ("W13", "schema evolution", "measured tests", "10/10 pass; bounded scope"),
    ]
    body = [
        r"\begin{tabular}{llll}",
        r"\toprule",
        r"Block & Purpose & Evidence & Paper boundary \\",
        r"\midrule",
    ]
    for row in rows:
        body.append(" & ".join(tex_escape(c) for c in row) + r" \\")
    body.extend([r"\bottomrule", r"\end{tabular}"])
    write_file(
        out_dir / "w10-evidence-overview.tex",
        table_env("tab:w10-evidence-overview", "Frozen W10 evidence blocks.", "\n".join(body)),
    )


def render_w6(w6: str, out_dir: Path) -> None:
    rows = md_table_after(w6, "## Aggregate Matrix")
    body = [
        r"\begin{tabular}{lrrrrrl}",
        r"\toprule",
        r"Variant & Store GiB & L0 files & Ops & Candidate L0 & Read bytes & Avg us \\",
        r"\midrule",
    ]
    for row in rows:
        body.append(
            " & ".join(
                [
                    r"\texttt{" + tex_escape(row["variant"]) + "}",
                    tex_escape(row["store GiB"]),
                    tex_escape(row["L0 files"]),
                    tex_escape(row["ops/repeat"]),
                    short_metric(row["candidate L0 mean+/-std"]),
                    short_metric(row["read bytes mean+/-std"]),
                    short_metric(row["avg us mean+/-std"]),
                ]
            )
            + r" \\"
        )
    body.extend([r"\bottomrule", r"\end{tabular}"])
    write_file(
        out_dir / "w10-sf100-matrix.tex",
        table_env(
            "tab:w10-sf100-matrix",
            "W6 SF100 matrix regenerated from raw runner artifacts.",
            "\n".join(body),
            r"\scriptsize",
        ),
    )

    rss_rows = {row["variant"]: row["max RSS GiB"] for row in md_table_after(w6, "## Import RSS")}
    body = [
        r"\begin{tabular}{lp{0.18\linewidth}p{0.62\linewidth}}",
        r"\toprule",
        r"Gate & Decision & Paper use \\",
        r"\midrule",
        r"Latency & FALLBACK & \texttt{budg-b64} mean is lower than schema, but 1-stddev intervals overlap; no stable latency-superiority claim. \\",
        rf"RSS & GO & measured RSS: schema/naive={float(rss_rows['schema']) / float(rss_rows['naive']):.2f}x and \texttt{{budg-b64}}/naive={float(rss_rows['budg-b64']) / float(rss_rows['naive']):.2f}x. \\",
        r"\bottomrule",
        r"\end{tabular}",
    ]
    write_file(
        out_dir / "w10-gate-summary.tex",
        table_env("tab:w10-gates", "W6 Gate 1/2 interpretation.", "\n".join(body)),
    )


def render_w7(w7: str, out_dir: Path) -> None:
    rows = md_table_after(w7, "## Migration Summary")
    body = [
        r"\begin{tabular}{lrrrl}",
        r"\toprule",
        r"Variant & A hot flush & B hot flush & Changed & Paper boundary \\",
        r"\midrule",
    ]
    for row in rows:
        boundary = "self-tuning evidence" if row["variant"] == "feedback-only" else "control"
        body.append(
            " & ".join(
                [
                    r"\texttt{" + tex_escape(row["variant"]) + "}",
                    tex_escape(row["phase A hot-compaction flush"]),
                    tex_escape(row["phase B hot-compaction flush"]),
                    tex_escape(row["selected ranges changed"]),
                    tex_escape(boundary),
                ]
            )
            + r" \\"
        )
    body.extend([r"\bottomrule", r"\end{tabular}"])
    write_file(
        out_dir / "w10-w7-workload-shift.tex",
        table_env(
            "tab:w10-w7",
            "W7 workload-shift migration summary; input is real-SF30-derived.",
            "\n".join(body),
        ),
    )

    costs = [r for r in md_table_after(w7, "## Rewrite Cost") if r["variant"] == "feedback-only"]
    body = [
        r"\begin{tabular}{lrrrr}",
        r"\toprule",
        r"Phase & Hot compactions & Input & Output & Write amplification \\",
        r"\midrule",
    ]
    for row in costs:
        body.append(
            " & ".join(
                [
                    tex_escape(row["phase"]),
                    tex_escape(row["hot compactions"]),
                    tex_escape(row["compaction input"]),
                    tex_escape(row["compaction output"]),
                    tex_escape(row["write amplification"]),
                ]
            )
            + r" \\"
        )
    body.extend([r"\bottomrule", r"\end{tabular}"])
    write_file(
        out_dir / "w10-w7-rewrite-cost.tex",
        table_env("tab:w10-w7-cost", "W7 feedback rewrite-cost accounting.", "\n".join(body)),
    )


